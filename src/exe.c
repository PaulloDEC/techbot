/*
 * exe.c - load the user's original DN1.EXE (or DN2/DN3.EXE) at runtime.
 *
 * The decompiled game never embeds the original's text, tables or artwork.
 * Instead it unpacks the user's own LZEXE 0.91-compressed DN1.EXE in memory
 * and reads constant data (strings, jump curves, level/backdrop name tables,
 * initial values of initialised globals) straight out of its data segment.
 */
#include "dn1.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

uint8_t *exe_image;            /* unpacked load module (code + data)          */
uint32_t exe_image_size;
uint8_t *exe_ds;               /* = exe_image + DGROUP*16 (original DS:0000)  */

/* DS segment relative to the load module: DN1 17E3h, DN2 17E7h, DN3 17E9h
 * (read from the startup code's "mov dx, DGROUP") */
static unsigned dgroup_para = 0x17E3u;
#define DGROUP_PARA dgroup_para
int episode = 1;               /* 1..3: which episode's EXE is loaded          */
uint16_t heap_map_seg = 0x3661;   /* see HEAP_MAP_SEG in dn1.h                 */

/* ---------------------------------------------------------------- episodes
 * The three episodes are the same program built with different text: the
 * port names data by its DN1.EXE offset, and episode_map.c (generated by
 * tools/episode_map.py) says where that data lives in DN2/DN3.EXE. */
static const EpisodeMap *emap;
static uint16_t ds_map(uint16_t off)
{
    int lo, hi;
    if (!emap || off < 0x0F00) return off;          /* tables and early data never moved */
    lo = 0; hi = emap->nrefs - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (emap->refs[m][0] == off) return emap->refs[m][1];
        if (emap->refs[m][0] < off) lo = m + 1; else hi = m - 1;
    }
    for (lo = 0; lo < emap->nruns; lo++)
        if (off >= emap->runs[lo][0] && off < emap->runs[lo][0] + emap->runs[lo][2])
            return (uint16_t)(off - emap->runs[lo][0] + emap->runs[lo][1]);
    if (off >= 0x4ECA) return (uint16_t)(off + emap->bss_shift);
    return off;
}
/* the reverse: an episode offset back to the DN1 offset the port uses */
static uint16_t ds_unmap(uint16_t off)
{
    int i;
    if (!emap || off < 0x0F00) return off;
    for (i = 0; i < emap->nrefs; i++) if (emap->refs[i][1] == off) return emap->refs[i][0];
    for (i = 0; i < emap->nruns; i++)
        if (off >= emap->runs[i][1] && off < emap->runs[i][1] + emap->runs[i][2])
            return (uint16_t)(off - emap->runs[i][1] + emap->runs[i][0]);
    return 0xFFFF;
}
uint16_t ds_episode_off(uint16_t dn1_off) { return ds_map(dn1_off); }

static uint16_t rd16(const uint8_t *p) { return (uint16_t)(p[0] | (p[1] << 8)); }

/* LZEXE 0.91 decompressor. Returns malloc'd load module or NULL. */
static uint8_t *unlzexe91(const uint8_t *d, uint32_t len, uint32_t *outlen)
{
    uint16_t hdrp = rd16(d + 8), cs = rd16(d + 0x16);
    uint32_t p = (uint32_t)hdrp * 16, cap = 0x30000, n = 0;
    uint8_t *out;
    uint16_t buf; int cnt;
    if (len < 0x20 || memcmp(d + 0x1C, "LZ91", 4) != 0) return NULL;
    (void)cs;
    out = (uint8_t *)malloc(cap);
#define GETW() (p += 2, rd16(d + p - 2))
#define GETB() (d[p++])
#define BIT(b) do { b = buf & 1; if (--cnt == 0) { buf = GETW(); cnt = 16; } else buf >>= 1; } while (0)
    buf = GETW(); cnt = 16;
    for (;;) {
        int b, ln; int span;
        if (p >= len) break;
        BIT(b);
        if (b) { out[n++] = GETB(); continue; }
        BIT(b);
        if (!b) {
            int b1, b2; BIT(b1); BIT(b2);
            ln = ((b1 << 1) | b2) + 2;
            span = (int)(GETB() | 0xFF00) - 0x10000;
        } else {
            int lo = GETB(), hi = GETB();
            span = (int)(lo | ((hi & ~7) << 5) | 0xE000) - 0x10000;
            ln = (hi & 7) + 2;
            if (ln == 2) {
                ln = GETB();
                if (ln == 0) break;
                if (ln == 1) continue;
                ln++;
            }
        }
        while (ln--) { out[n] = out[(long)n + span]; n++; }
        if (n + 0x200 > cap) { cap *= 2; out = (uint8_t *)realloc(out, cap); }
    }
#undef GETW
#undef GETB
#undef BIT
    *outlen = n;
    return out;
}

int exe_load(const char *path)
{
    FILE *f = fopen(path, "rb");
    long len; uint8_t *d;
    if (!f) return 0;
    fseek(f, 0, SEEK_END); len = ftell(f); fseek(f, 0, SEEK_SET);
    d = (uint8_t *)malloc((size_t)len);
    if (fread(d, 1, (size_t)len, f) != (size_t)len) { fclose(f); free(d); return 0; }
    fclose(f);
    if (len > 0x20 && memcmp(d + 0x1C, "LZ91", 4) == 0) {
        exe_image = unlzexe91(d, (uint32_t)len, &exe_image_size);
    } else {                     /* already-unpacked MZ */
        uint32_t hdr = (uint32_t)rd16(d + 8) * 16;
        exe_image_size = (uint32_t)len - hdr;
        exe_image = (uint8_t *)malloc(exe_image_size + 0x10000);
        memcpy(exe_image, d + hdr, exe_image_size);
    }
    free(d);
    if (!exe_image || exe_image_size < 0x18000u || exe_image[0] != 0xBA) return 0;
    /* which episode: the startup code loads DGROUP into DX first thing */
    dgroup_para = rd16(exe_image + 1);
    switch (dgroup_para) {
    /* the far heap follows the stack segment (SS 255Eh / 2570h / 2553h), which
     * moves with the size of the data */
    case 0x17E3: episode = 1; emap = NULL;           heap_map_seg = 0x3661; break;
    case 0x17E7: episode = 2; emap = &episode_map_2; heap_map_seg = 0x3661 + 0x12; break;
    case 0x17E9: episode = 3; emap = &episode_map_3; heap_map_seg = 0x3661 - 0x0B; break;
    default: return 0;                                  /* not a Duke Nukem 1 v1.0 EXE */
    }
    /* pad so that any DS offset < 0x10000 is addressable */
    exe_image = (uint8_t *)realloc(exe_image, DGROUP_PARA * 16u + 0x10000u);
    memset(exe_image + exe_image_size, 0, DGROUP_PARA * 16u + 0x10000u - exe_image_size);
    exe_ds = exe_image + DGROUP_PARA * 16u;
    return 1;
}

const char *ds_str(uint16_t off)   { return (const char *)(exe_ds + ds_map(off)); }
/* a string named by its offset in the loaded episode's own data (episode-only text) */
const char *ds_ep_str(uint16_t off) { return (const char *)(exe_ds + off); }
uint8_t     ds_u8(uint16_t off)    { return exe_ds[ds_map(off)]; }
/* (port) offset of a pointer into the original data segment, or -1 */
int ds_offset_of(const char *p)
{
    uint16_t o;
    if (!exe_ds || (const uint8_t *)p < exe_ds || (const uint8_t *)p >= exe_ds + 0x10000) return -1;
    o = ds_unmap((uint16_t)((const uint8_t *)p - exe_ds));
    return o == 0xFFFF ? -1 : o;
}
uint16_t    ds_u16(uint16_t off)   { return rd16(exe_ds + ds_map(off)); }

/* far pointer stored in the data segment that points into DGROUP -> string */
const char *ds_farstr(uint16_t off)
{
    uint16_t o = rd16(exe_ds + off), s = rd16(exe_ds + off + 2);
    if (s == 0 && o == 0) return NULL;
    return (const char *)(exe_ds + o);     /* already an offset in this episode's data */
}
