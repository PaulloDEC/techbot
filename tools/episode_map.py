#!/usr/bin/env python3
"""
episode_map.py - derive the data-offset translation DN1.EXE -> DN2/DN3.EXE.

The three episode executables are the same program built with different text,
so most data moved by a few hundred bytes.  The C port names data by its DN1
offset (ds_str(0x2F85) etc.); this tool finds where each of those lives in
another episode:

  1. code references: the two code segments are aligned instruction by
     instruction (operands masked); in every matched pair an immediate or
     displacement that differs (and is not a relocated segment value) gives
     "DN1 offset X is episode offset Y" - exact, because it is the same
     instruction of the same routine using its own string;
  2. data blocks: the initialised parts of the two data segments are aligned
     byte-wise; equal runs map offset for offset (tables, initial values,
     unchanged strings).

Output: src/episode_map.c with one table pair per episode (numbers only - no
game data).  Usage:
  python3 tools/episode_map.py DN1.EXE DN2.EXE DN3.EXE > src/episode_map.c
(packed or unpacked EXEs; needs capstone)
"""
import sys, struct, re, difflib
from capstone import Cs, CS_ARCH_X86, CS_MODE_16

sys.path.insert(0, __file__.rsplit('/', 1)[0])

def unlz(d):
    if d[0x1C:0x20] != b'LZ91':
        return d
    import io, contextlib, tempfile, os, subprocess
    here = os.path.dirname(os.path.abspath(__file__))
    with tempfile.TemporaryDirectory() as t:
        a, b = os.path.join(t, 'a.exe'), os.path.join(t, 'b.exe')
        open(a, 'wb').write(d)
        subprocess.run([sys.executable, '-I', os.path.join(here, 'unlzexe.py'), a, b],
                       check=True, stdout=subprocess.DEVNULL)
        return open(b, 'rb').read()

def load(path):
    d = unlz(open(path, 'rb').read())
    h = struct.unpack('<H', d[8:10])[0] * 16
    nrel = struct.unpack('<H', d[6:8])[0]; ro = struct.unpack('<H', d[24:26])[0]
    rel = set()
    for i in range(nrel):
        o, s = struct.unpack('<HH', d[ro + i * 4:ro + i * 4 + 4]); rel.add(s * 16 + o)
    img = d[h:]
    assert img[0] == 0xBA, 'unexpected entry code'
    dgroup = struct.unpack('<H', img[1:3])[0]
    return img, rel, dgroup

md = Cs(CS_ARCH_X86, CS_MODE_16)
md.detail = True

def dis(img, end):
    out = []; i = 0
    while i < end:
        ins = list(md.disasm(img[i:i + 16], i, count=1))
        if not ins:
            out.append((i, 'db', '', 1, ())); i += 1; continue
        x = ins[0]
        # immediate / displacement field positions: imm_offset, disp_offset
        out.append((i, x.mnemonic, x.op_str, x.size, (x.imm_offset, x.imm_size, x.disp_offset, x.disp_size)))
        i += x.size
    return out

def norm(t):
    op = re.sub(r'0x[0-9a-f]+', 'N', t[2]); op = re.sub(r'\b\d+\b', 'N', op)
    return t[1] + ' ' + op

def fields(img, t):
    """(value, position) of the immediate and displacement of an instruction"""
    a, _, _, size, f = t
    res = []
    if not f: return res
    imo, ims, dio, dis_ = f
    if dio and dis_ == 2: res.append((struct.unpack('<H', img[a + dio:a + dio + 2])[0], a + dio))
    if imo and ims == 2: res.append((struct.unpack('<H', img[a + imo:a + imo + 2])[0], a + imo))
    return res

def episode(base, other):
    A, ra, ga = base; B, rb, gb = other
    da = dis(A, ga * 16); db = dis(B, gb * 16)
    sm = difflib.SequenceMatcher(None, [norm(t) for t in da], [norm(t) for t in db], autojunk=False)
    pairs = {}
    conflicts = 0
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag != 'equal': continue
        for k in range(i2 - i1):
            x = da[i1 + k]; y = db[j1 + k]
            if x[1].startswith('j') or x[1] in ('call', 'lcall', 'ljmp', 'loop', 'retf', 'ret'): continue
            fx = fields(A, x); fy = fields(B, y)
            if len(fx) != len(fy): continue
            for (vx, px), (vy, py) in zip(fx, fy):
                if vx == vy or px in ra or py in rb: continue
                if vx < 0x0F00: continue          # tables/low data never moved
                if vx in pairs and pairs[vx] != vy: conflicts += 1; continue
                pairs[vx] = vy
    # byte alignment of the initialised data (up to DN1's BSS start 4ECAh)
    DA = A[ga * 16:ga * 16 + 0x4ECA]; DB = B[gb * 16:gb * 16 + 0x5200]
    sm2 = difflib.SequenceMatcher(None, DA, DB, autojunk=False)
    blocks = [(m.a, m.b, m.size) for m in sm2.get_matching_blocks() if m.size >= 4]
    # BSS: shift of the uninitialised data (first BSS variable referenced by code)
    bss = sorted((vx, vy - vx) for vx, vy in pairs.items() if vx >= 0x4ECA)
    return pairs, blocks, bss, conflicts

def main():
    base = load(sys.argv[1])
    print('/* episode_map.c - generated by tools/episode_map.py: where data that the')
    print(' * port names by its DN1.EXE offset lives in DN2.EXE / DN3.EXE.  Offsets only. */')
    print('#include "dn1.h"\n')
    for n, path in enumerate(sys.argv[2:], start=2):
        pairs, blocks, bss, conf = episode(base, load(path))
        deltas = sorted(set(d for _, d in bss))
        print('/* episode %d: %d code references (%d conflicting ignored), %d equal data runs; BSS shift %s */'
              % (n, len(pairs), conf, len(blocks), deltas))
        print('static const uint16_t ep%d_refs[][2] = {' % n)
        items = sorted(pairs.items())
        for i in range(0, len(items), 6):
            print('    ' + ' '.join('{0x%04X,0x%04X},' % p for p in items[i:i + 6]))
        print('};')
        print('static const uint16_t ep%d_runs[][3] = {' % n)
        for i in range(0, len(blocks), 5):
            print('    ' + ' '.join('{0x%04X,0x%04X,0x%04X},' % b for b in blocks[i:i + 5]))
        print('};')
        print('const EpisodeMap episode_map_%d = { ep%d_refs, (int)(sizeof ep%d_refs / sizeof ep%d_refs[0]),'
              ' ep%d_runs, (int)(sizeof ep%d_runs / sizeof ep%d_runs[0]), %d };\n'
              % (n, n, n, n, n, n, n, deltas[0] if len(deltas) == 1 else 0))
        print('episode %d: %d refs, %d runs, %d conflicts, bss %s' % (n, len(pairs), len(blocks), conf, deltas), file=sys.stderr)

main()
