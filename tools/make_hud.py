#!/usr/bin/env python3
"""
make_hud.py - turn the Immersive HUD art (resources/hud/*.png) into
src/hud_data.h: palette-slot indices (0..15, 255 = transparent), so the HUD
is drawn in the game's own palette and fades with it.

    python tools/make_hud.py            (from the project folder; needs Pillow)

hud_43.png, hud_43_alt.png       320 x 200: the 4:3 bars (Immersive / Immersive Alt)
hud_wide.png, hud_wide_alt.png   424 x 200: the 16:9 bars (with the D-U-K-E box)
                 (only the rows the bars cover are stored)
gun_power_N.png  16 x 7, N = 1..4 shots
Every opaque pixel must be one of the 16 EGA colours.
"""
import os, sys
from PIL import Image

EGA = [(0x00, 0x00, 0x00), (0x00, 0x00, 0xAA), (0x00, 0xAA, 0x00), (0x00, 0xAA, 0xAA),
       (0xAA, 0x00, 0x00), (0xAA, 0x00, 0xAA), (0xAA, 0x55, 0x00), (0xAA, 0xAA, 0xAA),
       (0x55, 0x55, 0x55), (0x55, 0x55, 0xFF), (0x55, 0xFF, 0x55), (0x55, 0xFF, 0xFF),
       (0xFF, 0x55, 0x55), (0xFF, 0x55, 0xFF), (0xFF, 0xFF, 0x55), (0xFF, 0xFF, 0xFF)]
here = os.path.dirname(os.path.abspath(__file__))
res = os.path.join(here, '..', 'resources', 'hud')

def indices(path):
    im = Image.open(path).convert('RGBA')
    w, h = im.size
    out = []
    for y in range(h):
        row = []
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a < 128: row.append(255); continue
            if (r, g, b) not in EGA: sys.exit('%s: (%d,%d) colour %s is not an EGA colour' % (path, x, y, (r, g, b)))
            row.append(EGA.index((r, g, b)))
        out.append(row)
    return w, h, out

def table(name, rows):
    s = 'static const uint8_t %s[%d][%d] = {\n' % (name, len(rows), len(rows[0]))
    for r in rows: s += '    {' + ','.join(str(v) for v in r) + '},\n'
    return s + '};\n'

BARS = [('hud_43', 'hud_43.png', 320), ('hud_43_alt', 'hud_43_alt.png', 320),
        ('hud_wide', 'hud_wide.png', 424), ('hud_wide_alt', 'hud_wide_alt.png', 424)]
loaded = []
for name, fn, width in BARS:
    w, h, rows = indices(os.path.join(res, fn))
    assert (w, h) == (width, 200), '%s must be %d x 200' % (fn, width)
    loaded.append((name, rows))
top = min(y for _, rows in loaded for y in range(200) if any(v != 255 for v in rows[y]))
out = ['/* hud_data.h - generated by tools/make_hud.py from resources/hud/ (PNG files): */',
       '/* palette slots, 255 = transparent.  Do not edit. */',
       '#define HUD_BAR_TOP %d   /* first row of the bars in the 200-line picture */' % top]
for name, rows in loaded: out.append(table(name, rows[top:]))
for n in range(1, 5):
    pw, ph, p = indices(os.path.join(res, 'gun_power_%d.png' % n))
    assert (pw, ph) == (16, 7), 'gun_power_%d.png must be 16 x 7' % n
    out.append(table('hud_power%d' % n, p))
open(os.path.join(here, '..', 'src', 'hud_data.h'), 'w').write('\n'.join(out))
print('src/hud_data.h: bars from row %d' % top)
